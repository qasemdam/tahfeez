<?php

namespace App\Http\Controllers\Api\V1;

use App\Domain\Evaluation\Services\WeekPeriodResolver;
use App\Domain\Reports\DTOs\DashboardSummary;
use App\Domain\Reports\DTOs\MonthlyReport;
use App\Domain\Reports\DTOs\WeeklyReport;
use App\Domain\Reports\Export\ExportResult;
use App\Domain\Reports\Export\ReportExportService;
use App\Domain\Reports\Support\ReportPeriodResolver;
use App\Http\Controllers\Controller;
use App\Http\Requests\Api\V1\DashboardExportRequest;
use App\Http\Requests\Api\V1\MonthlyReportExportRequest;
use App\Http\Requests\Api\V1\WeeklyReportExportRequest;
use Illuminate\Http\Response;
use Illuminate\Support\Facades\Gate;

/**
 * Report exports (BR-RPT-03).
 *
 * The controller resolves the period, authorizes, delegates the file to the
 * export service and turns the result into a response. It holds no report logic
 * and never inspects the generated bytes.
 *
 * Scope is not re-implemented here: the query objects apply the actor's group
 * scope, so an out-of-scope filter yields an empty report rather than another
 * center's data.
 */
class ReportExportController extends Controller
{
    public function weekly(
        WeeklyReportExportRequest $request,
        WeekPeriodResolver $weekResolver,
        ReportPeriodResolver $periods,
        ReportExportService $service,
    ): Response {
        $actor = $request->user();
        Gate::authorize('export', WeeklyReport::class);

        $center = $actor->center;

        $period = $periods->week(
            $request->input('week_key'),
            $request->input('week_start_date'),
            $weekResolver,
            $center->timezone,
            $center->weekly_evaluation_start_day,
        );

        return $this->file($service->weekly(
            actor: $actor,
            center: $center,
            period: $period,
            groupId: $this->filterId($request->input('group_id')),
            studentId: $this->filterId($request->input('student_id')),
            format: $request->exportFormat(),
        ));
    }

    public function monthly(
        MonthlyReportExportRequest $request,
        ReportPeriodResolver $periods,
        ReportExportService $service,
    ): Response {
        $actor = $request->user();
        Gate::authorize('export', MonthlyReport::class);

        $center = $actor->center;
        $month = $periods->month((string) $request->input('month'), $center->timezone);

        return $this->file($service->monthly(
            actor: $actor,
            center: $center,
            month: $month,
            groupId: $this->filterId($request->input('group_id')),
            studentId: $this->filterId($request->input('student_id')),
            format: $request->exportFormat(),
        ));
    }

    public function dashboard(
        DashboardExportRequest $request,
        ReportPeriodResolver $periods,
        ReportExportService $service,
    ): Response {
        $actor = $request->user();
        Gate::authorize('export', DashboardSummary::class);

        $center = $actor->center;
        $month = $periods->month((string) $request->input('month'), $center->timezone);

        return $this->file($service->dashboard(
            actor: $actor,
            center: $center,
            month: $month,
            groupId: $this->filterId($request->input('group_id')),
            format: $request->exportFormat(),
        ));
    }

    /**
     * The file is already in memory: the response only names it. The content
     * type and the disposition belong to the format, not to the controller.
     */
    private function file(ExportResult $result): Response
    {
        return response($result->contents, 200, [
            'Content-Type' => $result->format->contentType(),
            'Content-Disposition' => sprintf(
                '%s; filename="%s"',
                $result->format->disposition(),
                $result->filename,
            ),
            'Cache-Control' => 'private, no-store',
            'X-Content-Type-Options' => 'nosniff',
        ]);
    }

    private function filterId(mixed $value): ?int
    {
        return $value === null || $value === '' ? null : (int) $value;
    }
}
